#!/usr/bin/env python3
"""Build the §3.2 throughput table from the re-voxelisation run logs.

Wall-clock per stage, per city and per resolution, with output volume. The
run log records one line per batch; batches are consecutive slices of the
manifest, and every batch turns out to hold exactly one city, so the city is
read off the first manifest row of each slice.

    ./throughput_table.py 0.25:revoxelise.log:out 0.5:revoxelise_050.log:out_050

Each argument is <voxel_m>:<log>:<out_dir>. Prints a plain table and the
LaTeX body for the manuscript.
"""
import csv, re, sys, collections
from pathlib import Path

HERE = Path(__file__).resolve().parent
MANIFEST = HERE.parents[1] / "tensorbuilding/shards/manifest.csv"
BATCH = 250

LINE = re.compile(
    r"batch_(\d{4}): (\d+) bldgs, (\d+) voxel rows.*?"
    r"\[upgrade ([\d.]+)s\s+obj ([\d.]+)s\s+vox ([\d.]+)s\]")


def thin(n):
    """Integer with LaTeX thin-space thousands separators."""
    return f"{int(n):,}".replace(",", r"\,")


def city_of_batch():
    rows = list(csv.DictReader(open(MANIFEST, newline="")))
    out = {}
    for bi in range(0, (len(rows) + BATCH - 1) // BATCH):
        sl = rows[bi * BATCH:(bi + 1) * BATCH]
        names = {r["kreis"].split(",")[0] for r in sl}
        if len(names) != 1:
            raise SystemExit(f"batch_{bi:04d} spans {len(names)} cities; "
                             "per-city attribution is not valid for this manifest")
        out[bi] = sl[0]["kreis"].split(",")[0]
    return out


def parse(log, out_dir, city):
    agg = collections.defaultdict(
        lambda: dict(n=0, rows=0, up=0.0, obj=0.0, vox=0.0, nb=0, bytes=0))
    seen = 0
    for line in open(log):
        m = LINE.search(line)
        if not m:
            continue
        bi, n, rows, up, obj, vox = (float(x) for x in m.groups())
        bi = int(bi)
        a = agg[city[bi]]
        a["n"] += int(n); a["rows"] += int(rows)
        a["up"] += up; a["obj"] += obj; a["vox"] += vox; a["nb"] += 1
        f = Path(out_dir) / f"batch_{bi:04d}_voxels.csv"
        if f.exists():
            a["bytes"] += f.stat().st_size
        seen += 1
    if not seen:
        raise SystemExit(f"{log}: no batch lines matched")
    return agg


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    city = city_of_batch()
    runs = []
    for spec in sys.argv[1:]:
        vox, log, out_dir = spec.split(":")
        runs.append((float(vox), parse(log, out_dir, city)))
    runs.sort(key=lambda r: -r[0])

    for vm, agg in runs:
        print(f"\n=== {vm} m ===")
        print(f"{'city':<12}{'bldgs':>7}{'upgrade':>9}{'obj':>7}{'voxelize':>10}"
              f"{'total':>8}{'s/bldg':>8}{'voxel rows':>14}{'output':>10}")
        tot = collections.Counter()
        for c, a in sorted(agg.items(), key=lambda kv: -kv[1]["vox"]):
            t = a["up"] + a["obj"] + a["vox"]
            print(f"{c:<12}{a['n']:>7}{a['up']:>8.0f}s{a['obj']:>6.0f}s"
                  f"{a['vox']:>9.0f}s{t:>7.0f}s{t/a['n']:>8.2f}{a['rows']:>14,}"
                  f"{a['bytes']/2**30:>9.2f}G")
            tot.update(a)
        t = tot["up"] + tot["obj"] + tot["vox"]
        print("-" * 85)
        label = f"all {len(agg)}" if len(agg) != 5 else "all five"
        print(f"{label:<12}{tot['n']:>7}{tot['up']:>8.0f}s{tot['obj']:>6.0f}s"
              f"{tot['vox']:>9.0f}s{t:>7.0f}s{t/tot['n']:>8.2f}{tot['rows']:>14,}"
              f"{tot['bytes']/2**30:>9.2f}G")

    print("\n% --- LaTeX body: per city, per stage, per resolution ---")
    print("% generated by postthesis/r0_resolution/throughput_table.py")
    for vm, agg in runs:
        tot = collections.Counter()
        print(f"\\midrule\n\\multicolumn{{8}}{{l}}{{\\itshape voxel edge {vm:g}\\,m}} \\\\")
        for c, a in sorted(agg.items(), key=lambda kv: -kv[1]["vox"]):
            t = a["up"] + a["obj"] + a["vox"]
            print(f"\\quad {c} & {thin(a['n'])} & {a['up']:.0f} & {a['obj']:.0f} & "
                  f"{thin(round(a['vox']))} & {t/a['n']:.2f} & "
                  f"{a['rows']/1e6:.1f} & {a['bytes']/2**30:.2f} \\\\")
            tot.update(a)
        t = tot["up"] + tot["obj"] + tot["vox"]
        print(f"\\quad\\textbf{{all five}} & \\textbf{{{thin(tot['n'])}}} & {tot['up']:.0f} & "
              f"{tot['obj']:.0f} & \\textbf{{{thin(round(tot['vox']))}}} & "
              f"\\textbf{{{t/tot['n']:.2f}}} & \\textbf{{{tot['rows']/1e6:.1f}}} & "
              f"\\textbf{{{tot['bytes']/2**30:.2f}}} \\\\")

    print("\n% --- LaTeX body: one row per resolution ---")
    for vm, agg in runs:
        tot = collections.Counter()
        for a in agg.values():
            tot.update(a)
        t = tot["up"] + tot["obj"] + tot["vox"]
        print(f"{vm:g}\\,m & {thin(tot['n'])} & {tot['up']:.0f} & {tot['obj']:.0f} & "
              f"{thin(round(tot['vox']))} & {thin(round(t/60))} & {t/tot['n']:.2f} & "
              f"{tot['rows']/1e6:.1f} & {tot['bytes']/2**30:.1f} \\\\")


if __name__ == "__main__":
    main()
